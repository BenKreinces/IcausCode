static void ETH_PHY_ResetPulse(void)
{
  HAL_GPIO_WritePin(ETH_NRST_GPIO_Port, ETH_NRST_Pin, GPIO_PIN_RESET);
  HAL_Delay(2);   // comfortably longer than the PHY minimum reset pulse
  HAL_GPIO_WritePin(ETH_NRST_GPIO_Port, ETH_NRST_Pin, GPIO_PIN_SET);
  HAL_Delay(2);   // give straps / PHY state time to settle before MDIO access
}

static HAL_StatusTypeDef ETH_MDIO_MinimalInit(void)
{
  heth_mdio_test.Instance = ETH;
  heth_mdio_test.Init.MediaInterface = HAL_ETH_RMII_MODE;

  /* If your project has a real HAL_ETH_MspInit() in stm32h7xx_hal_msp.c,
     this should configure ETH GPIOs (MDC/MDIO/RMII pins) and clocks.
     If that function is still weak/empty, this call does nothing. */
  HAL_ETH_MspInit(&heth_mdio_test);

  __HAL_RCC_ETH1MAC_CLK_ENABLE();
  __HAL_RCC_ETH1TX_CLK_ENABLE();
  __HAL_RCC_ETH1RX_CLK_ENABLE();
  __HAL_RCC_SYSCFG_CLK_ENABLE();

  HAL_SYSCFG_ETHInterfaceSelect(SYSCFG_ETH_RMII);
  (void)SYSCFG->PMCR;

  /* Software reset of ETH MAC/DMA block */
  SET_BIT(ETH->DMAMR, ETH_DMAMR_SWR);
  gPhyDbg.dmamr_after_swr_set = ETH->DMAMR;

  uint32_t t0 = HAL_GetTick();
  while (READ_BIT(ETH->DMAMR, ETH_DMAMR_SWR) != 0U)
  {
    if ((HAL_GetTick() - t0) > 1000U)
    {
      gPhyDbg.swr_timeout = 1U;
      gPhyDbg.dmamr_after_swr_wait = ETH->DMAMR;
      return HAL_TIMEOUT;
    }
  }

  gPhyDbg.dmamr_after_swr_wait = ETH->DMAMR;
  gPhyDbg.hclk_hz = HAL_RCC_GetHCLKFreq();

  HAL_ETH_SetMDIOClockRange(&heth_mdio_test);
  gPhyDbg.macmdioar_after_clk_cfg = ETH->MACMDIOAR;

  return HAL_OK;
}

static void ETH_PHY_ScanAll(void)
{
  uint32_t val;
  uint32_t addr;

  gPhyDbg.first_candidate_addr = -1;
  gPhyDbg.candidate_mask = 0U;
  gPhyDbg.ksz8081_mask = 0U;

  for (addr = 0; addr < 32; addr++)
  {
    gPhyDbg.stat2[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 2, &val);
    gPhyDbg.reg2[addr] = val & 0xFFFFU;

    /* Only treat it as a real candidate if reg2 is sane */
    if ((gPhyDbg.stat2[addr] == HAL_OK) &&
        (gPhyDbg.reg2[addr] != 0x0000U) &&
        (gPhyDbg.reg2[addr] != 0xFFFFU))
    {
      gPhyDbg.candidate_mask |= (1UL << addr);

      if (gPhyDbg.first_candidate_addr < 0)
      {
        gPhyDbg.first_candidate_addr = (int32_t)addr;
      }

      if (gPhyDbg.reg2[addr] == 0x0022U)
      {
        gPhyDbg.ksz8081_mask |= (1UL << addr);
      }

      gPhyDbg.stat3[addr]  = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 3,  &val);
      gPhyDbg.reg3[addr]   = val & 0xFFFFU;

      gPhyDbg.stat17[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 17, &val);
      gPhyDbg.reg17[addr]  = val & 0xFFFFU;

      gPhyDbg.stat0[addr]  = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 0,  &val);
      gPhyDbg.reg0[addr]   = val & 0xFFFFU;

      /* Read BMSR twice */
      gPhyDbg.stat1a[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 1,  &val);
      gPhyDbg.reg1a[addr]  = val & 0xFFFFU;

      gPhyDbg.stat1b[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 1,  &val);
      gPhyDbg.reg1b[addr]  = val & 0xFFFFU;

      gPhyDbg.stat1e[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 0x1E, &val);
      gPhyDbg.reg1e[addr]  = val & 0xFFFFU;

      gPhyDbg.stat1f[addr] = HAL_ETH_ReadPHYRegister(&heth_mdio_test, addr, 0x1F, &val);
      gPhyDbg.reg1f[addr]  = val & 0xFFFFU;
    }
    else
    {
      gPhyDbg.stat3[addr]  = 0xFFFFFFFFU;
      gPhyDbg.stat17[addr] = 0xFFFFFFFFU;
      gPhyDbg.stat0[addr]  = 0xFFFFFFFFU;
      gPhyDbg.stat1a[addr] = 0xFFFFFFFFU;
      gPhyDbg.stat1b[addr] = 0xFFFFFFFFU;

      gPhyDbg.reg3[addr]   = 0U;
      gPhyDbg.reg17[addr]  = 0U;
      gPhyDbg.reg0[addr]   = 0U;
      gPhyDbg.reg1a[addr]  = 0U;
      gPhyDbg.reg1b[addr]  = 0U;
    }
  }
}
