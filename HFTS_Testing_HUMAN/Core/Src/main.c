static void u16_to_be(uint16_t v, uint8_t b[2]) { b[0] = (uint8_t)(v >> 8); b[1] = (uint8_t)(v); }
static uint32_t be24_to_u32(const uint8_t b[3]) { return ((uint32_t)b[0] << 16) | ((uint32_t)b[1] << 8) | (uint32_t)b[2]; }


void ad7124_bringup_one_channel_continuous(ad7124_t *dev)
{

    // 1) Reset interface / device
    ad7124_reset(dev);

    uint8_t error_en[3] = { 0x00, 0x00, 0x00 };
    g_hal = ad7124_write_reg(dev, 0x07, error_en, 2);
    // 2) CONFIG_0: bipolar=1 (optional), buffers on, internal ref, PGA=1
    // Bits: Bipolar (bit11), REF_BUFP (8), REF_BUFM (7), AIN_BUFP (6), AIN_BUFM (5),
    // REF_SEL (4:3) = 10 internal ref, PGA (2:0) = 000 gain 1:contentReference[oaicite:14]{index=14}
    uint16_t config0 =
        (1u << 11) |       // Bipolar (choose 0 if you want unipolar)
        (0u << 8)  | (1u << 7) |  // REF buffer off
        (1u << 6)  | (1u << 5) |  // AIN buffers on
        (0u << 3)  |       // REF_SEL = 00 (refin1+/- reference):contentReference[oaicite:15]{index=15}
        (0u << 0);         // PGA = 000 => gain 1:contentReference[oaicite:16]{index=16}

    uint8_t cfgb[2];
    u16_to_be(config0, cfgb);
    g_hal = ad7124_write_reg(dev, 0x19, cfgb, 2); // CONFIG_0 = 0x19

    // 3) FILTER_0: start with a sane default (leave as reset value or write your desired ODR)
    // If your driver has AD7124_REG_FILTER0, use that constant.
    // Here we just write the datasheet reset value 0x060180 (sinc4 default) as a known baseline:contentReference[oaicite:17]{index=17}
    //uint8_t filt0[3] = { 0x06, 0x01, 0x80 };
    //g_hal = ad7124_write_reg(dev, /*FILTER_0 addr*/ AD7124_REG_FILTER0, filt0, 3);
    uint8_t filt0[3] = { 0x06, 0x01, 0x80 };
    g_hal = ad7124_write_reg(dev, 0x21, filt0, 3);
    // 4) CHANNEL_0: enable it, select Setup 0, select inputs.
    // CHANNEL register: Enable bit15, Setup bits14:12, AINP bits9:5, AINM bits4:0:contentReference[oaicite:18]{index=18}
    // Example: differential AIN0/AIN1 (AINP=0, AINM=1) which is also the default reset mapping.
    uint16_t ch0 =
        (1u << 15) |       // enable channel
        (0u << 12) |       // setup 0
        (2u << 5)  |       // AINP = AIN2
        (3u << 0);         // AINM = AIN

    uint8_t chb[2];
    u16_to_be(ch0, chb);
    g_hal = ad7124_write_reg(dev, 0x09, chb, 2);  // CHANNEL_0 = 0x09

    // 5) ADC_CONTROL: enable internal reference + continuous conversion mode.
    // Mode=0000 is continuous conversion:contentReference[oaicite:19]{index=19}.
    // REF_EN bit enables internal reference:contentReference[oaicite:20]{index=20}.
    // POWER_MODE and CLK_SEL are also in ADC_CONTROL:contentReference[oaicite:21]{index=21}.
    //
    // Example: REF_EN=1, POWER_MODE=full power (10), Mode=0000, CLK_SEL=internal (00).
    // See Table 67/68 descriptions for field meanings:contentReference[oaicite:22]{index=22}:contentReference[oaicite:23]{index=23}
    uint16_t adc_ctrl =
        (0u << 8)  |        // REF_EN disabled
        (2u << 6)  |        // POWER_MODE = 10 (full power)
        (0u << 2)  |        // Mode = 0000 (continuous conversion)
        (0u << 0);          // CLK_SEL = 00 (internal clock)

    uint8_t acb[2];
    u16_to_be(adc_ctrl, acb);
    g_hal = ad7124_write_reg(dev, 0x01, acb, 2);  // ADC_CONTROL = 0x01

}

void loop_poll_data(ad7124_t *dev)
{
    // optional: read STATUS each time (0x00)
    g_hal = ad7124_read_reg(dev, 0x00, (uint8_t*)&g_status_byte, 1);

    // read DATA register (24-bit) at 1 Hz and just see it moving
    g_hal = ad7124_read_reg(dev, 0x02, (uint8_t*)g_data_bytes, 3);
    g_data_raw24 = be24_to_u32((const uint8_t*)g_data_bytes);
}

